@pytest.mark.parametrize("y1,y2,expected",[(5,3,0),(3,5,2),(4,4,0),(-3,-1,2),(-1,-3,0)])
def test_ordered_reversed_equal(y1,y2,expected):
    gap,value=diagnostic.relaxation_pair(y1,y2)
    assert gap==y2-y1 and value==expected


def test_exact_projection_formula_and_bound_direction():
    # Independent rational projection onto p1>=p2, not the diagnostic formula.
    for y1,y2 in [(Fraction(3),Fraction(5)),(Fraction(-3,2),Fraction(5,4)),(Fraction(4),Fraction(4)),(Fraction(6),Fraction(1))]:
        if y1>=y2: p1,p2=y1,y2
        else: p1=p2=(y1+y2)/2
        exact=(p1-y1)**2+(p2-y2)**2
        assert diagnostic.relaxation_pair(y1,y2)[1]==float(exact)
        for q1 in range(-4,9):
            for q2 in range(-4,q1+1):
                assert exact <= (Fraction(q1)-y1)**2+(Fraction(q2)-y2)**2


def test_noisy_manufactured_model_bound_is_not_adequacy():
    # Fixed artificial PSD diagonal tensor, exact directions, deterministic noise.
    directions=np.eye(3); eigenvalues=np.array([.0003,.0007,.0012])
    d=np.sum(directions**2*eigenvalues,axis=1)
    low=100*(.7*np.exp(-1000*d)+.3*np.exp(-3.))
    high=100*(.7*np.exp(-2000*d)+.3*np.exp(-6.))
    assert np.all(high<=low)
    for a,b in zip(low,high): assert diagnostic.relaxation_pair(a,b)[1]==0
    observed_low=low+np.array([-50.,0.,-10.])
    observed_high=high+np.array([35.,-2.,15.])
    relaxed=sum(diagnostic.relaxation_pair(a,b)[1] for a,b in zip(observed_low,observed_high))
    feasible_sse=float(np.sum((low-observed_low)**2+(high-observed_high)**2))
    assert 0 < relaxed <= feasible_sse
    # These reversals were generated by noise, not by a model violation.


def artificial_gradients():
    return np.array([0.,1000.,1000.,2000.,2000.]),np.array([[0.,0.,0.],[1.,0.,0.],[0.,1.,0.],[1.,0.,0.],[0.,1.,0.]]),np.arange(5)


def test_exact_pairing_retains_all_indices_and_permutations():
    b,g,v=artificial_gradients()
    assert diagnostic.exact_pairing(b,g,v,pairs=2)==(0,[(1,3),(2,4)])
    g[[3,4]]=g[[4,3]]
    assert diagnostic.exact_pairing(b,g,v,pairs=2)==(0,[(1,4),(2,3)])


@pytest.mark.parametrize("mutation",["tiny_change","antipodal","duplicate_low","duplicate_high","nan","zero_direction","bad_shell","bad_volume"])
def test_invalid_pairing_fails_closed(mutation):
    b,g,v=artificial_gradients()
    if mutation=="tiny_change": g[3,0]=np.nextafter(1.,2.)
    elif mutation=="antipodal": g[3]=-g[3]
    elif mutation=="duplicate_low": g[2]=g[1]
    elif mutation=="duplicate_high": g[4]=g[3]
    elif mutation=="nan": g[3,0]=math.nan
    elif mutation=="zero_direction": g[1]=0
    elif mutation=="bad_shell": b[3]=1999
    elif mutation=="bad_volume": v[3]=7
    with pytest.raises(ValueError): diagnostic.exact_pairing(b,g,v,pairs=2)


