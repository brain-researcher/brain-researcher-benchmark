def test_all_manufactured_rows_and_unchanged_mean_sse_denominator(tmp_path,monkeypatch):
    b,g,v=artificial_gradients()
    selected={"coordinates":[[1,2,3],[4,5,6]],"indices":[7,8]}
    # Two different measured b0 values exercise per-voxel normalization.
    signal=np.array([[10.,3.,5.,5.,4.],[20.,7.,2.,7.,8.]])
    monkeypatch.setattr(diagnostic,"authenticate",lambda paths,contract:(selected,signal,{"ref_bvecs":g},0,[(1,3),(2,4)]))
    contract={"support":{"coordinates":2,"pairs_per_coordinate":2},"scope":"manufactured fixture","release_boundary":"not scientific data"}
